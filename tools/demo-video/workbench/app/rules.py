def family(key, detail=''):
    if key.startswith('observer.'): return 'observer'
    if key.startswith('delivery.'): return 'delivery'
    # Owner precondition takes precedence over auth. A skipped login is not a 401.
    if 'owner' in key or detail == 'backend-owner-invalid': return 'owner'
    if key.endswith('.auth'): return 'auth'
    if 'loaded-version' in key: return 'version'
    if key.endswith('.clean'): return 'dirty'
    if key.endswith(('.http', '.openapi')): return 'network'
    if key.endswith(('.pin', '.branch', '.head')): return 'pin'
    return 'unknown'

def diagnose(key, status, detail):
    group = family(key, detail)
    title, impact, hypothesis, paths = RULES[group]
    priority = 'P1' if group in ('auth', 'network', 'observer') and status == 'fail' else 'P2'
    return dict(engine=VERSION, family=group, title=title, impact=impact, hypothesis=hypothesis,
                priority=priority, confidence='待核验假设，不是已确认根因',
                solutions=[dict(id=f'{group}-{n}', rank=n, title=p[0], kind=p[1], steps=p[2],
                    verification=p[3], applicableWhen='需先满足步骤中的证据与授权条件。',
                    risk='诊断只读；改配置、重启、发布或投递必须另行授权。' if p[1] in ('root-cause','mitigation','prevention') else '只读检查；日志须脱敏，不反复尝试凭据。',
                    rollback='此界面不执行操作；实际变更须预先保留配置/版本并准备恢复流程。',
                    cost='低：只读核对' if p[1]=='diagnostic' else '中：需负责人确认并验证')
                    for n,p in enumerate(paths,1)])
